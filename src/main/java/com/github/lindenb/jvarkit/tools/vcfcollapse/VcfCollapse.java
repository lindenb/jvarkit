@Program(name="vcfcollapse",
description="collapse vcf generated with vcfconcat --merge",
keywords={"vcf"},
creationDate= "20260724",
modificationDate = "20260724",
jvarkit_amalgamion = true,
menu="VCF Manipulation"
	)
public class VcfCollapse extends OnePassVcfLauncher {

	
	private boolean same(final VariantContext vc1,final VariantContext vc2) {
		if(!(vc1.contigsMatch(vc2) && vc1.getStart()==vc2.getStart()  && vc1.getReference().equals(vc2.getReference()))) {
			return false;
			}
		
		
		return true;
		}
	
	private boolean isBetter(final Genotype gt, final Genotype old) {
		if(old==null ) return true;
		if(!gt.isNoCall() && old.isNoCall()) return true;
		if(gt.isNoCall() && !old.isNoCall()) return false;
		
		if(!gt.isFiltered() && old.isFiltered()) return true;
		if(gt.isFiltered() && !old.isFiltered()) return false;
		
		if(gt.hasGQ() && old.hasGQ()) {
			return gt.getGQ()>old.getGQ();
			}
		if(gt.hasDP() && old.hasDP()) {
			return gt.getDP() > old.getDP();
			}
		if(gt.hasPL() && old.hasPL()) {
			final int m1 = Arrays.stream( gt.getPL()).max().orElse(0);
			final int m2 = Arrays.stream(old.getPL()).max().orElse(0);
			return m1>m2;
			}
		if(gt.hasAltAllele() && !old.hasAltAllele()) return true;
		if(!gt.hasAltAllele() && old.hasAltAllele()) return false;
		return false;
		}
	
	private static class SVSignature {
		String svtype;
		int svlen;
		int end;
		@Override
		public int hashCode() {
			return Objects.hash(svtype,svlen,end);
			}
		@Override
		public boolean equals(Object obj) {
			final SVSignature other=(SVSignature)obj;
			return this.svtype.equals(other.svtype) && 
					(this.svlen == other.svlen) && 
					(this.end == other.end);
			}
		}
	
	private Collection<List<VariantContext>> second_split(boolean sv_flag,final List<VariantContext> row) {
		if(sv_flag) {
			final Map<SVSignature,List<VariantContext>>  ret= new HashMap<>();
			for(VariantContext vc:row) {
				final SVSignature sig = new SVSignature();
				sig.svtype= vc.getAttributeAsString(VCFConstants.SVTYPE, ".");
				sig.svlen = vc.getAttributeAsInt("SVLEN", 0);
				sig.end = vc.getEnd();
				List<VariantContext> L = ret.get(sig);
				if(L==null) {
					L=new ArrayList<VariantContext>();
					ret.put(sig,L);
					}
				L.add(vc);
				}
			
			return ret.values();
			}
		return Collections.singletonList(row);
		}
	
	@Override
	protected int doVcfToVcf(String inputName,final VCFIterator iterin,final VariantContextWriter out) {
		final VCFHeader h0 = iterin.getHeader();
		final VCFHeader h1 = new VCFHeader(h0);
		final boolean sv_flag = h0.getInfoHeaderLine(VCFConstants.SVTYPE)!=null &&  h0.getInfoHeaderLine("SVLEN")!=null;
		JVarkitVersion.getInstance().addMetaData(this, h1);
		out.writeHeader(h1);
		try(EqualIterator<VariantContext> eqiter=new EqualIterator<VariantContext>(iterin, (V1,V2)->(same(V1,V2)?0:1))) {
			while(eqiter.hasNext()) {
				final List<VariantContext> row0 = eqiter.next();
				/* give a chance to break things for SV, etc... */
				for(List<VariantContext> row : second_split(sv_flag,row0)) {
					final VariantContext first = row.get(0);
					final Set<Allele> alleles = new HashSet<>();
					
					final Map<String,Genotype> sample2genotype = new HashMap<>(h0.getNGenotypeSamples());
					for(VariantContext ctx:row) {
						alleles.addAll(ctx.getAlleles());
						
						for(Genotype g: ctx.getGenotypes()) {
							final String sn = g.getSampleName();
							if(isBetter(g,sample2genotype.get(sn))) {
								sample2genotype.put(sn, g);
								}
							}
						}
					
					final VariantContextBuilder vcb= new VariantContextBuilder(this.getProgramName(), first.getContig(), first.getStart(),  first.getEnd(), alleles);
					if(first.hasAttribute(VCFConstants.END_KEY)) {
						vcb.attribute(VCFConstants.END_KEY, first.getAttribute(VCFConstants.END_KEY));
						}
					if(first.hasAttribute(VCFConstants.SVTYPE)) {
						vcb.attribute(VCFConstants.SVTYPE, first.getAttribute(VCFConstants.SVTYPE));
						}
					if(first.hasAttribute("SVLEN")) {
						vcb.attribute("SVLEN", first.getAttribute("SVLEN"));
						}
					vcb.genotypes(sample2genotype.values().stream().collect(Collectors.toList()));
					out.add(vcb.make());
					}
				}
			
			}
		return 0;
		}
	
public static void main(final String[] args) {
	new VcfCollapse().instanceMainWithExit(args);
	}
}
